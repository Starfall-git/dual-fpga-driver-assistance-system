// rgb_sharpen.v —— RGB 域亮度反锐化掩模 (unsharp mask)
//
// 位置: 插在 debayer_top_wbg_2to1 **之后**、ti60f225_oob_top 的
//       pos_vs/vid_cnt/hdmi_tx_*data 消费块 **之前**:
//         debayer_top_wbg_2to1 -> [ rgb_sharpen ] -> hdmi_tx_*data
//
// ---------------------------------------------------------------------------
// 为什么放在 gamma 之后 (而不是之前)
//   gamma_lut_v1 的底部斜率极陡 (lut(1)=15), 在 gamma **之前**做锐化会把阴影区的
//   锐化量放大好几倍 —— 而那正是噪声最大的地方, 结果是一堆暗部斑块。放在 gamma
//   之后, 锐化量在所有亮度上是同一个尺度, 暗部不会被放大。
//
// ---------------------------------------------------------------------------
// 算法
//   Y     = (54*R + 183*G + 18*B + 128) >> 8         // BT.709, 系数和 = 255
//   Y_ce  = 中心像素的**原始**亮度 (未经水平 1-2-1)
//   h     = 行方向 1-2-1: (Y[k-1] + 2*Y[k] + Y[k+1] + 2) >> 2
//   blur  = 列方向 1-2-1: (h_up + 2*h_ce + h_dn + 2) >> 2
//   delta = Y_ce - blur                               // 有符号, -255..255
//   out   = clamp(ch + sign(delta) * round(|delta| * K / 2^14), 0, 255)
//
//   BT.709 的三系数和是 **255 不是 256**, 所以纯白 Y = (255*255+128)>>8 = 254。
//   这只把亮度整体缩了不到 1/256, 对锐化没有任何影响: 平坦区 blur 恒等于 Y_ce
//   (理由见下), delta 精确为 0, 与系数和是多少无关。
//
//   **同一个 delta 加给 R/G/B 三个通道** —— 只锐化亮度、不动色相。逐通道各算各的
//   会产生彩边 (三通道过冲量不同 -> 边缘出现伪色)。
//
//   展开就是标准的 3x3 高反差保留核 (中心 16 减二项式模糊核), 各向同性:
//       -1  -2  -1
//       -2 +12  -2   /16
//       -1  -2  -1
//   系数和为 0 -> 平坦区 delta 精确为 0, 不放大平坦区噪声。
//
//   *** 中心项必须是 Y_ce, 不能是 h_ce ***
//   早期版本写的是 delta = h_ce - blur, 展开后等价于
//       -1  -2  -1
//       +2  +4  +2   /16
//       -1  -2  -1
//   那是个**纯垂直**的算子: 三项全在**同一列**、只差行, 于是只要亮度沿列不变
//   (垂直边、竖笔画、物体的左右轮廓), h_up == h_ce == h_dn, delta **精确等于 0**,
//   这半个方向的边一点都锐化不到。上板现象就是"开关和增益都看不出效果"。
//   中心项取原始 Y_ce 才有水平方向的响应 —— 不要再改回 h_ce。
//
//   与旧写法相比, **横边的响应逐位不变**: 横边所在行沿水平方向平坦, 三点的 Y 相等,
//   于是 h_ce = (4Y+2)>>2 = Y = Y_ce, 新旧 delta 完全相同。这次改的是"补上竖边
//   响应", 不是"改动横边的强度"。
//   (两个例外都是既有的、已被 SKIP_LINES=2 排除的取舍: 每行首/末像素的水平 1-2-1
//    会越界到邻行; 帧首 2 行 h_up/h_dn 来自未初始化的 RAM。)
//
// ---------------------------------------------------------------------------
// *** 已知失效: 画面右侧白条 (2026-10-07 上板实测) ***
//
//   上面那句"每行首/末像素的水平 1-2-1 越界到邻行, 影响远小于 1 个输出级"
//   在 K 提上去以后**不成立**。行末那个伪边沿的 |delta| 正比于
//   (本行末像素 - 下行首像素) 之差, 真实图像里可以有几十级。K=1.83 时 amt
//   能到 180+, 三通道一起钳到 255 —— 每行末列都变白, 连起来就是画面右侧
//   一条竖直白条。
//
//   曾试过用 coring + "低幅度 4 倍"折线 (T=2, M=24) 来只放大真细节:
//   行末伪边沿的 mag 恰好落进 4 倍段, 白条反而更明显, **该改动已回退**。
//   结论: 在行末伪边沿被处理掉之前, 别再往"加大 K"或"给小幅度额外增益"上使劲。
//
//   正解 (未做, 要动延迟链): 把每行末 1~2 列的锐化量强制归零 —— 那几列的
//   delta 本来就不代表画面。或者把水平 1-2-1 改成逐行独立的实现 (见下 (a) 段)。
//
// ---------------------------------------------------------------------------
// "为什么光把 K 拉满也不够" 的量化解释
//
//   对 1 像素的理想台阶, |delta| = 台阶高度/4, 过冲 = |delta|*K。K 挡位到 4.0,
//   于是 32 级台阶最多也就 32 级过冲。可双线性 debayer 出来的边**不是台阶、
//   是斜坡**, 而二阶差分算子对线性斜坡的响应趋近于 0 —— 真实图像的 |delta|
//   主要落在过渡的拐点上, 典型只有几级。实测 (水平 1-2-1, 64 级对比度的边):
//
//     边的形状                   |delta| 峰值   占 "高度/4"
//     理想 1 像素台阶                16         100%
//     2 像素过渡                      8          50%
//     4 像素线性斜坡                  4          25%
//     纯线性斜坡 (无突变)             2          12.5%   (只在两端)
//     模糊边 (0,4,20,52,64)           5          31%     <- 真实边在这里
//
//   所以线性放大到顶也只是个位数的过冲, 还要被 adj_ch 的钳位再吃掉一部分。
//   但上面那条白条说明: 单纯加增益走不通, 瓶颈在这个算子的行末行为和钳位上。
//
//   *** 顶层实参不要写超过 65535 的值 ***
//   P_SHARP_GAIN 是 [15:0], 在**调用点**写 16'd95535 这种数, 字面量当场就回绕成
//   29999 (K=1.83), 综合报告里会看到一个你根本没写过的参数值 —— 现象就是"增益
//   已经拉满了却还是不够"。K 的物理上限就是 4.0, 对应 16'd65535。
//
// ---------------------------------------------------------------------------
//   代价: 中心项不再经水平预平滑, delta 的白噪声增益从 0.375*sigma 升到 0.800*sigma
//   (核的 Sum(k^2): 0.140625 -> 0.640625)。整级输出噪声 ~ sqrt(1 + (K*sigma_g)^2):
//   K=0.5 时约 1.02x -> 1.08x, K=1.0 时约 1.07x -> 1.28x。嫌噪就把 P_SHARP_GAIN 调小。
//
//   Y_ce 与 blur 都天然落在 [0,255] (h 与 blur 都是权重和 = 4 的加权平均),
//   各 8 位足够, delta = Y_ce - blur 仍需 9 位。
//
// ---------------------------------------------------------------------------
// 为什么这里不用 isp_line_window.v
//   它的 data_i 硬连成 20 位 (2 x 10 位像素), RGB 是 48 位/字塞不进去; 强行用就得
//   再造一条 2 行的 RGB 对齐 FIFO。所以这里用**另一个**既有原语
//   rtl/debayer/line_buffer.v —— 它只有 2 个行抽头, 与 isp_line_window 的 5 行 x 3 字
//   是完全不同的东西, 不构成 lw_model.m 文件头警告的那种"第二份拷贝"。
//
//   抽头含义 (用法与 raw_to_rgb.v:236-272 一致, 时延另行推导, 见下):
//     o_p_11 = 第 N-2 行 (上)
//     o_p_00 = 第 N-1 行 (中)  <- 中心像素取这一行的 RGB
//     o_p_01 = 第 N-0 行 (下)
//   三者在**同一字地址**上严格同拍, 行号依次差 1。o_p_11 之所以是 N-2 而不是 N,
//   是因为读口取的是当前行所在 bank 的**旧内容** (WRITE_MODE_1 = "READ_FIRST"),
//   也就是同一个地址在 2 行前写进去的数据。
//
// ---------------------------------------------------------------------------
// line_buffer 的 payload 打包 (64 位 = P_DEPTH(32) * 2)
//     [63:56] = 偶列亮度 h_even   [55:48] = 奇列亮度 h_odd
//     [47:24] = 奇列像素 {B,G,R}  [23:0]  = 偶列像素 {B,G,R}
//   打包约定与 debayer_top_wbg_2to1.v:248-249 的 rgb_datax2_o 一致:
//   低位 = 偶列 (原 datax4 的低字节), 高位 = 奇列。
//   把亮度与 RGB 塞进**同一个** RAM 字, 是为了让中心和它的模糊值天然同拍 ——
//   分成两条延迟链就必须手工配对, 那是错拍的经典来源。
//
// ---------------------------------------------------------------------------
// 时延记账 —— 分两段, 两段的"延迟单位"不一样, 别混着数
//
// (a) 水平级 (r1 -> r2): 单位是**拍**
//   记 w_c 在第 c 拍出现在 i_datax2 上。取任意拍 c:
//     r1_rgb = w_{c-1}    r1_ye = Ye(c-1)    r1_yo = Yo(c-1)
//     r1_yo_d1 = Yo(c-2)  i_datax2 = w_c  ->  组合可得 w_ye_now = Ye(c)
//     w_h_e_sum = Yo(c-2) + 2*Ye(c-1) + Yo(c-1) + 2 = h_even(c-1)   <- 组合
//     w_h_o_sum = Ye(c-1) + 2*Yo(c-1) + Ye(c)   + 2 = h_odd (c-1)   <- 组合
//   第 c 拍末把这两项连同 r1_rgb 一起寄存:
//     r2 级 (第 c+1 拍): r2_rgb = w_{c-1}, r2_h_e/r2_h_o = h(c-1)
//   三者都属于同一个字 c-1, 对齐无误 -> 本级时延 = (c+1) - (c-1) = **2 拍**
//   (注意别数错: 这里串联了 r1/r2 两级寄存器, 而奇列用到的 Ye(c) 是**向当前拍
//    借**的组合值, 相当于向前偷了一拍, 所以两级寄存器只换来 2 拍时延。)
//   这一段的关键产出是: **rgb 与 h 打进去时就是同一个字的**, 后面搭同一辆车,
//   天然不会再错开。
//
// (b) line_buffer 级: 单位是**行**, 不是拍 (这里最容易想错, 务必看仔细)
//   线缓存本质是一个 bank 选择器 + 一块双 bank RAM, 不是 2 拍延迟线。读口 addr2 =
//   {~r_addr1_sel, r_addr1} 取的是**另一个 bank** —— 也就是**上一行**同一字地址的
//   内容; RAM 自己再给 2 拍 (READ_FIRST + OUTPUT_REG 都为 TRUE, 见
//   true_dual_port_ram.v:70-78 与 :123-129)。所以取任意拍 t, 令当拍写入的
//   (行 m, 字 j) 为输入流第 n 个字:
//     o_p_01 = r_p_01_1P = i_p(t-2)                        = 输入第 n    个字 (行 m  , 字 j-2)
//     o_p_00 = ram[{~sel(t-2), addr1(t-2)}]                = 输入第 n-WORDS个字 (行 m-1, 字 j-2)
//     o_p_11 = ram[{ sel(t-2), addr1(t-2)}] (READ_FIRST)   = 输入第 n-2*WORDS 个字 (行 m-2, 字 j-2)
//   三个抽头**同一字地址**, 行号依次差 1, 与文件头上面那句
//   "o_p_11 = N-2 行 / o_p_00 = N-1 行 / o_p_01 = N-0 行" 一致。
//
//   于是本模块的不变式是 **out[n] = in[n - WORDS]** (整行位移),
//     而不是"延迟 N 拍" —— 旁路模式同理 (P_BYPASS 只换 o_datax2 的来源,
//     不换任何一级的拍数)。
//
//   *** 这条"标志与数据同拍"是本模块的输出约定, 不是 debayer 的 ***
//   标志同样走 2 拍延迟进入 line_buffer, 由它自己的 o_de/o_valid 输出, 与 o_p_*
//   同拍。因此本模块的输出标志与输出数据**同拍**, 输入侧的相对关系原样保持。
//   debayer_top_wbg_2to1 内部那个"标志比数据早 1 拍"的错拍是 raw_to_rgb 自己产生
//   的, 是标定的一部分 (SKIP_WORDS=2/SKIP_LINES=2 就是配着它标定的)。本模块在
//   **下游**, 只要把 4 个标志与数据整体平移同样的量, 那个错拍就原封不动。
//   绝不要"顺手"在这里把标志多打一拍去对齐 —— 见 debayer_top_wbg_2to1.v:15-21。
//
//   另: 输出字覆盖每行全部 WORDS 个 (t-2 在行内从 t_m 走到 t_m+WORDS-1, 地址恰好
//   走完 0..WORDS-1), 没有行末丢像素。这是行**标签**整体下移一行, 属于纯平移,
//   与 debayer 自身的行对齐 (由 SKIP_LINES 标定) 无关。
//
//   *** 这条"标志与数据同拍"是本模块的输出约定, 不是 debayer 的 ***
//   debayer_top_wbg_2to1 内部那个"标志比数据早 1 拍"的错拍是 raw_to_rgb 自己产生
//   的, 是标定的一部分 (SKIP_WORDS=2/SKIP_LINES=2 就是配着它标定的)。本模块在
//   **下游**, 只要把 4 个标志与数据整体平移同样的拍数, 那个错拍就原封不动。
//   绝不要"顺手"在这里把标志多打一拍去对齐 —— 见 debayer_top_wbg_2to1.v:15-21。
//
// ---------------------------------------------------------------------------
// 边界取舍 (与既有流水线保持一致, 不是本模块新引入的)
//   1. 水平 1-2-1 只在**行内**做, 行首/行尾各越界 1 个像素:
//      行首第一拍的左邻居取到的是上一行最后一个字的奇列 (r1_yo_d1 里残留的
//      上一行末字), 行尾最后一拍的右邻居取到的是下一行第一个字的偶列
//      (向当前拍借的那个 w_ye_now)。每行各 1 个像素, 且左右边缘相邻行通常
//      相近, 影响远小于 1 个输出级。
//      没做像素复制是因为复制的值根本没被存下来 —— line_buffer 里放的是"本行
//      的 h", 邻行的末字要单独引入一拍寄存。要做得干净就得把整条链换成
//      isp_line_window 那种带 pad 的窗口, 那是另一个量级的改动, 收益只有
//      每行 2 个像素。
//   2. 帧首 2 行的 RAM 内容未初始化 (RAM_INIT_FILE=""), o_p_00/o_p_11 读到的是
//      空的, 所以这几行输出无意义 —— 需要**早于**当前行的两行数据, 而帧首没有。
//      (帧末不受影响: 抽头全在"当前行及更早", 不需要未来行。)
//      既有标定的 SKIP_LINES=2 本来就把这几行排除在采集窗口外。
//   3. 本模块的 line_buffer 未做流控 (无 in_req), 与 debayer 里的用法一致。
/////////////////////////////////////////////////////////////////////////////

module rgb_sharpen
#(
	parameter [15:0]	P_SHARP_GAIN	= 16'd8192,		// Q2.14; 8192=0.5, 量程 0..65535 = 0..4.0
													// *** 实参别写 >65535, 会在字面量处回绕 ***
	// parameter			P_BYPASS		= 1'b0,			// 1 = 只走延迟链, 不锐化
	parameter integer	X_CNT_WIDTH		= 10			// 每行字数 960 -> 10 位
)
(
	input						i_pclk,
	input						i_arstn,		// 低有效; line_buffer 是同步复位, 见下
	input  						P_BYPASS,
	input						i_vs,
	input						i_hs,
	input						i_de,
	input						i_valid,
	input	[47:0]				i_datax2,		// {奇列{B,G,R}, 偶列{B,G,R}}

	output						o_vs,
	output						o_hs,
	output						o_de,
	output						o_valid,
	output	[47:0]				o_datax2
);

	//======================================================================
	// 亮度: BT.601, 系数和 = 256, 加 128 做四舍五入
	//   77*255 + 150*255 + 29*255 + 128 = 65408, 32 位表达式不会溢出
	//======================================================================

	// function [7:0] luma;
    // input [7:0] r;
    // input [7:0] g;
    // input [7:0] b;
    // reg [15:0] sum;  // 16bit中间寄存器，足够容纳最大值65408
	// begin
	// 	sum  = 16'(77 * r) + 16'(150 * g) + 16'(29 * b) + 16'd128;
	// 	luma = sum >> 8;
	// end
	// endfunction

//======================================================================
// 亮度: BT.709 (1080P HD视频标准)
//   Y = round( (54*r + 183*g + 18*b) / 256 )
//   最大值:54*255 +183*255 +18*255 +128 = 65153，16位表达式不会溢出
//======================================================================
function [7:0] luma;
    input [7:0] r;
    input [7:0] g;
    input [7:0] b;
    reg [15:0] sum;
begin
    sum = 16'(54 * r) + 16'(183 * g) + 16'(18 * b) + 16'd128;
    luma = sum >> 8;
end
endfunction
	//======================================================================
	// 1. r1 级: 输入字 -> RGB + 双像素亮度 (1 拍)
	//======================================================================
	reg		[47:0]	r1_rgb;
	reg		[7:0]	r1_ye;					// 偶列亮度
	reg		[7:0]	r1_yo;					// 奇列亮度

	always @(posedge i_pclk)
	begin
		if (~i_arstn)
		begin
			r1_rgb	<= 48'd0;
			r1_ye	<= 8'd0;
			r1_yo	<= 8'd0;
		end else begin
			r1_rgb	<= i_datax2;
			r1_ye	<= luma(i_datax2[ 7: 0], i_datax2[15: 8], i_datax2[23:16]);
			r1_yo	<= luma(i_datax2[31:24], i_datax2[39:32], i_datax2[47:40]);
		end
	end

	// 偶列亮度再打 1 拍, 给偶列的左邻居用 (左邻居 = 前一个字的奇列)
	reg		[7:0]	r1_yo_d1;

	always @(posedge i_pclk)
	begin
		if (~i_arstn)
			r1_yo_d1	<= 8'd0;
		else
			r1_yo_d1	<= r1_yo;
	end

	//======================================================================
	// 2. r2 级: 行方向 1-2-1 (共 3 拍)
	//
	//    第 n+2 拍: r1_ye/r1_yo 是第 n+1 个字, r1_yo_d1 是第 n 个字的奇列,
	//    i_datax2 的偶列亮度是第 n+2 个字的 —— 于是第 n+1 个字的水平结果
	//    在这一拍组合算出, 与 r1_rgb (= 第 n+1 个字) 天然对齐。
	//    偶列: 左邻居 = 前一个字的奇列 (r1_yo_d1), 右邻居 = 本字的奇列 (r1_yo)
	//    奇列: 左邻居 = 本字的偶列 (r1_ye),     右邻居 = 下一个字的偶列
	//======================================================================
	wire	[7:0]	w_ye_now = luma(i_datax2[7:0], i_datax2[15:8], i_datax2[23:16]);

	wire	[9:0]	w_h_e_sum = {2'b0, r1_yo_d1} + {1'b0, r1_ye, 1'b0} + {2'b0, r1_yo} + 10'd2;
	wire	[9:0]	w_h_o_sum = {2'b0, r1_ye   } + {1'b0, r1_yo, 1'b0} + {2'b0, w_ye_now} + 10'd2;

	reg		[47:0]	r2_rgb;
	reg		[7:0]	r2_h_e;					// 偶列水平 1-2-1, 权重和 4 -> 仍 <= 255
	reg		[7:0]	r2_h_o;					// 奇列水平 1-2-1

	always @(posedge i_pclk)
	begin
		if (~i_arstn)
		begin
			r2_rgb	<= 48'd0;
			r2_h_e	<= 8'd0;
			r2_h_o	<= 8'd0;
		end else begin
			r2_rgb	<= r1_rgb;
			r2_h_e	<= w_h_e_sum[9:2];
			r2_h_o	<= w_h_o_sum[9:2];
		end
	end

	//======================================================================
	// 3. 标志延迟 2 拍, 与 r2_* 同拍 (见文件头的时延记账)
	//    vs/hs 是**电平**(下游拿 rgb_vs 当 HDMI 的场同步电平用, 见文件头),
	//    所以这里只是平移, 不产生任何脉冲或边沿。
	//======================================================================
	reg		[3:0]	r_flg_1;				// {vs, hs, de, valid}
	reg		[3:0]	r_flg_2;

	always @(posedge i_pclk)
	begin
		if (~i_arstn)
		begin
			r_flg_1	<= 4'b0000;
			r_flg_2	<= 4'b0000;
		end else begin
			r_flg_1	<= {i_vs, i_hs, i_de, i_valid};
			r_flg_2	<= r_flg_1;
		end
	end

	//======================================================================
	// 4. 2 行缓存 (64 位/字, 亮度与 RGB 同字搭车)
	//======================================================================
	wire	[63:0]	w_lb_p_11;
	wire	[63:0]	w_lb_p_00;
	wire	[63:0]	w_lb_p_01;
	wire	[X_CNT_WIDTH-1:0]	w_lb_x;		// 未用: 本模块不需要列计数

	line_buffer
	#(
		.P_DEPTH		(32			),			// -> PW = 64
		.X_CNT_WIDTH	(X_CNT_WIDTH)
	)
	inst_line_buffer_sharpen
	(
		.i_arstn	(i_arstn							),
		.i_pclk		(i_pclk								),

		.i_vsync	(r_flg_2[3]							),
		.i_hsync	(r_flg_2[2]							),
		.i_de		(r_flg_2[1]							),
		.i_valid	(r_flg_2[0]							),
		.i_p		({r2_h_e, r2_h_o, r2_rgb}			),

		.o_vsync	(o_vs								),
		.o_hsync	(o_hs								),
		.o_de		(o_de								),
		.o_valid	(o_valid							),
		.o_p_11		(w_lb_p_11							),
		.o_p_00		(w_lb_p_00							),
		.o_p_01		(w_lb_p_01							),
		.o_x		(w_lb_x								)
	);

	//======================================================================
	// 5. 一个像素的锐化量: {sgn, amt}
	//    blur (由三个 h 抽头) 与 delta = Y_ce - blur 都在这里算, 两个像素各调一次。
	//    Y_ce 由调用处从 w_lb_p_00 的 RGB 现算后传进来 (见本函数下方第 5 节末尾)。
	//======================================================================
	function [11:0] sharp_amt;
		input [7:0] y_ce;				// 中心像素的**原始**亮度, 不是 h_ce!
		input [7:0] h_up;
		input [7:0] h_ce;
		input [7:0] h_dn;
		reg   [9:0] sum;
		reg   [7:0] blr;
		reg   [8:0] dlt;
		reg   [8:0] mag;
		reg  [24:0] scl;
		begin
			sum = {2'b0, h_up} + {1'b0, h_ce, 1'b0} + {2'b0, h_dn} + 10'd2;
			blr = sum[9:2];								// (up + 2*ce + dn + 2) >> 2
			dlt = {1'b0, y_ce} - {1'b0, blr};			// 9 位补码, -255..255
			mag = dlt[8] ? (~dlt + 9'd1) : dlt;			// |delta|, 0..255
			scl = {16'b0, mag} * P_SHARP_GAIN + 25'd8192;	// 四舍五入后 >>14
			sharp_amt = {dlt[8], scl[24:14]};			// 11 位幅值足够 (<= 1020)
		end
	endfunction

	//======================================================================
	// 6. 逐通道加锐化量, 饱和到 [0,255]
	//    用 16 位中间量, 正负两支都留足余量, 靠最高位判下溢。
	//======================================================================
	function [7:0] adj_ch;
		input [7:0]  ch;
		input [13:0] amt;
		input        sgn;
		reg  [15:0]  wide;
		begin
			wide = sgn ? ({8'b0, ch} - {2'b0, amt}) : ({8'b0, ch} + {2'b0, amt});
			adj_ch = wide[15] ? 8'd0 : ((wide[14:0] > 15'd255) ? 8'd255 : wide[14:0]);
		end
	endfunction

	function [23:0] adj_pix;
		input [23:0] px;							// {B, G, R}
		input [13:0] amt;
		input        sgn;
		begin
			adj_pix = { adj_ch(px[23:16], amt, sgn),
						adj_ch(px[15: 8], amt, sgn),
						adj_ch(px[ 7: 0], amt, sgn) };
		end
	endfunction

	// 中心像素的**原始**亮度: 由 w_lb_p_00 里的 RGB 现算, 不额外占 line_buffer 的位宽。
	// w_lb_p_00[23:0] / [47:24] 正是下面 adj_pix 要调整的那两个像素, 与同字的
	// h (w_lb_p_00[63:56] / [55:48]) 天然同像素对齐 —— 中心项与中心像素不会错开。
	// 一次 luma() = 3 个常量乘 + 2 次加法, 起点是 line_buffer 的输出寄存器, 组合深度
	// 落在 vid_clk_dvi2 的 13.468ns 预算里。若将来时序吃紧要在这里补寄存器, 必须给
	// **旁路支路同样补一拍** (否则切 P_BYPASS 会整体跳拍/跳行), 见文件头 (b) 段。
	wire	[7:0]	w_y_ce_e = luma(w_lb_p_00[ 7: 0], w_lb_p_00[15: 8], w_lb_p_00[23:16]);
	wire	[7:0]	w_y_ce_o = luma(w_lb_p_00[31:24], w_lb_p_00[39:32], w_lb_p_00[47:40]);

	wire	[11:0]	w_amt_e = sharp_amt(w_y_ce_e, w_lb_p_11[63:56], w_lb_p_00[63:56], w_lb_p_01[63:56]);
	wire	[11:0]	w_amt_o = sharp_amt(w_y_ce_o, w_lb_p_11[55:48], w_lb_p_00[55:48], w_lb_p_01[55:48]);

	wire	[23:0]	w_pix_e = adj_pix(w_lb_p_00[23: 0], {3'b0, w_amt_e[10:0]}, w_amt_e[11]);
	wire	[23:0]	w_pix_o = adj_pix(w_lb_p_00[47:24], {3'b0, w_amt_o[10:0]}, w_amt_o[11]);

	assign	o_datax2 = P_BYPASS ? w_lb_p_00[47:0] : {w_pix_o, w_pix_e};

endmodule
