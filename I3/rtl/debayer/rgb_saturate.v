`timescale 1ns/1ps
/////////////////////////////////////////////////////////////////////////////
// rgb_saturate.v —— RGB 域饱和度 (色度增益) + 暗部色度门控
//
// 位置: 插在 rgb_sharpen **之后**、ti60f225_oob_top 的
//       pos_vs/vid_cnt/hdmi_tx_*data 消费块 **之前**:
//         debayer_top_wbg_2to1 -> rgb_sharpen -> [ rgb_saturate ] -> hdmi_tx_*data
//
// *** 本模块是 1 拍流水 (标志与数据同步延迟 1 拍), 不是组合直通。***
//     理由见第六节 —— 上一版是组合直通, 上板直接时序翻车。
//
// ===========================================================================
// 一、为什么要这一级 (病因与处方)
//   症状: 白平衡正常 (灰/白物体是中性色), 但红色"不够红、发灰发橙"。
//   "白正常"说明三个 WB 增益已经把中性色拉平了, 病因不在增益;"红发灰"是
//   **色度幅度不足** —— 亮红的 R 高、G/B 也偏高, 于是看起来是偏移的橙粉色
//   而不是红。定点通路里把色度压掉的主要环节是 raw_to_rgb.v 的双线性插值:
//   它本质是低通, 对色度是过度的平滑。
//
//   而 Y 保持的色度拉伸正好对上这个症状。取一个偏灰的亮红 R=230 G=120 B=100:
//     Y   = (77*230 + 150*120 + 29*100 + 128) >> 8 = 151
//     S=1.4 -> R = 151 + 79*1.4 = 261 -> 饱和到 255
//              G = 151 - 31*1.4 = 108
//              B = 151 - 51*1.4 =  80
//   G/R 由 0.52 掉到 0.42, 红色确实更红、更不像橙。注意 R 撞到 255 了 (见下)。
//
//   *** CCM 现在做在**外面**了 (2026-10-06 更新, 原"为什么不做 CCM"已过时) ***
//   上一版这里写的是: "3x3 色彩矩阵才是治'色相偏'的正规工具, 但没有色卡就标不出
//   系数, 所以只做饱和度"。现在 CCM 已经单独成模块 ——
//       rtl/debayer/rgb_ccm.v, 插在本模块**上游**
//       (rgb_sharpen -> rgb_ccm -> rgb_saturate -> hdmi_tx_*)
//   "没有色卡"这件事的解法不是不做, 而是换一个可调的自由度: 不拟合 9 个系数,
//   改成"给一个色相旋转角, 由 rtl/debayer/sim/ccm_gen.py 生成 9 个保 BT.601 亮度、
//   保中性色的 Q2.14 系数"。默认是恒等矩阵 (逐位直通)。
//
//   >>> 因此本模块的 P_RED_SHIFT 已由 2 改成 0 (关闭) <<<
//   色相只由 rgb_ccm 一处负责。两处都动色相会互相盖 —— 调 CCM 系数时看到的位移
//   就不是 CCM 单独造成的, 标定没法做。P_RED_SHIFT 的代码与不变式检查都保留着
//   (功能没删, 只是顶层关掉了), 将来要重新打开时仍然是对的。
//   好处之一: 下面那条 "S = 16384 必须逐位直通" 的红线不再需要
//   "仅当红色偏向关闭时成立"这个限定。
//
//   补充 (已经查过, 不要重复怀疑): 这一级**不会**把画面整体抬爆。
//   按 rawdata.hex 实测, BLC 后 R/G/B 均值 21.6/19.1/7.5, 最大 238;
//   三个 WB 增益放大后只有 0.06% / 0.20% / 0.07% 的像素裁到 255。
//   若上板看到"死白", 病因不在这里, 去查 gamma / 曝光。
//
// ===========================================================================
// 二、算法
//   Y     = (77*R + 150*G + 29*B + 128) >> 8     // BT.601, 与 rgb_sharpen 同一个定义
//   S     = sat_gain_at(Y)                        // 见第三节, 亮度相关的色度增益
//   d_c   = c - Y                                 // 有符号, -255..255
//   out_c = clamp( Y + round(d_c * S / 2^14), 0, 255 )
//
//   S 是 Q2.14 的色度增益, 只拉伸色度、保持 Y, 所以 *** 中性色恒不受影响 ***
//   (R==G==B 时 d_c 全为 0, 输出等于输入, 与 S 无关)。
//
//   *** S = 16384 (= 1.0) 必须逐位等于直通 ***, 这是恒等式而非近似:
//       d_c 与 Y 都是整数, 且 round(d_c * 16384 / 2^14) 精确等于 d_c ——
//       ((|d_c| << 14) + 8192) >> 14 == |d_c|, 因为 8192 < 16384 不进位;
//       于是 out_c = Y + (c - Y) = c。所以那个舍入常数只能是 8192 (2^13),
//       写成 16384 (2^14) 会让 S=1.0 时每个正向 delta 多 1 级, 整幅画面被抬亮,
//       而写成 4096 则会暗一级。这是一条机器可验的红线, 见
//       rtl/debayer/sim/tb_rgb_saturate.v 的检查 1。
//
// ===========================================================================
// 三、暗部色度门控 —— 本模块第二个用法, 也是"黑处红色噪点"的解
//
//   症状: 用户报"黑的地方出现了红色噪点"。
//
//   机理 (实测 rawdata.hex 整帧) : gamma_lut_v1 的表是纯 (k/2/255)^(1/2.2),
//   底部斜率极大 (lut(1)=15, lut(2)=21, lut(3)=25)。也就是说暗部**任何一个通道
//   1 个线性 LSB 的噪声, 到编码域就是 15 级**。R 与 G 各自独立浮动, 于是
//   R-G 的波动在暗部能到 ±20 级 —— 屏幕上就是暗处的红/绿彩色颗粒。
//   色度乘以 S 等于把这份波动乘以 S, 所以 *** 暗部必须让 S 降到 1 以下 ***,
//   否则本模块本身就在制造彩色噪点。
//
//   处方: S 随亮度变化, 暗部小、中间调大 ——
//     Y <= P_Y_LO : S = P_SAT_GAIN_LO   (很暗, 色度基本是噪声, 压掉)
//     Y >= P_Y_HI : S = P_SAT_GAIN      (中间调以上, 完整的饱和度)
//     中间        : 线性插值, 避免出现可见的饱和度突变边界
//
//   *** 门控对 Y >= P_Y_HI 的像素是逐位无影响的 *** —— 那时 sat_gain_at 恒等于
//   P_SAT_GAIN, 与关掉门控一模一样。这是"门控不碰中间调"的机器可验红线,
//   tb_rgb_saturate.v 的检查 5a 专门断言这条。
//
//   标定依据 (rawdata.hex 整帧, 暗部 R-G 的高频分量 std, 噪点=高频):
//     无门控 S=1.30              : 3.48
//     S_LO=0.50, Y_LO=32,Y_HI=80 : 1.61
//     S_LO=0.50, Y_LO=24,Y_HI=64 : 1.65   (效果几乎相同, 但覆盖区域大, 不取)
//     S_LO=0.50, Y_LO=32,Y_HI=96 : 1.60   <== 当前默认
//
//   *** 为什么 Y_HI 从 80 改成 96 ***: 纯粹为了让斜坡宽度 (P_Y_HI - P_Y_LO)
//   等于 64 = 2^6, 于是 sat_gain_at 里的除法被综合成**一次移位**, 不占 DSP、
//   也短一截组合路径 (见第六节的时序账)。代价是 80 <= Y < 96 这一小段的增益
//   从 1.30 变成 1.30 以下的一点点内插 (Y=88 处约 1.20), 幅度 8%, 肉眼不可见。
//   实测暗部 R-G 高频 std 是 1.60, 与 (32,80) 的 1.61 只差 0.01, 就是看不出差别。
//   红线相应地从"Y>=80 不受影响"挪到"Y>=96 不受影响", 由检查 5a 断言。
//   若把斜坡宽度改成非 2 的幂, 除法会退回成真的除法器 —— 能跑, 但白丢时序余量。
//
// ===========================================================================
// 四、为什么放在 gamma 之后
//
//   *** 曾经有一版这里写的"放在 gamma 之后暗部不会被额外放大"是错的。***
//   两种放法的编码域增量恒等:
//     gamma 前: 编码域增量 = d_lin * S * slope
//     gamma 后: 编码域增量 = d_lin * slope * S
//   其中 slope 是 gamma 在暗部的局部斜率, 两边是同一个数 —— 暗部放大倍数就是
//   同一个 S, 与模块放在 gamma 的哪一侧无关。暗部这个真问题由第三节的亮度门控
//   解决, 不是靠挪位置。
//
//   仍然放 gamma 之后的**真正理由**有两条, 都与"放大"无关:
//     1. 与 rgb_sharpen 保持同一个 Y 定义 (编码域 BT.601)。两个模块对"什么是 Y"
//        的认识不一致的话, 锐化与饱和度就会朝不同方向掰同一幅画。
//     2. 编码域近似感知均匀, 在这里做保 Y 的色度拉伸对应"视觉亮度不变";
//        而线性域的保 Y 在暗部会过度保守, 拉不动色度。
//
// ===========================================================================
// 五、饱和裁剪的已知取舍
//   亮而饱和的红色 (R 本来就接近 255) 在 S>1 时 R 会被裁到 255, 此时 Y 不再守恒,
//   色相会朝黄/橙方向轻微回摆 —— 这是"加法式"饱和度控制的固有行为, 所有消费级
//   "鲜艳"模式都是这个做法。若上板后发现高饱和红色发闷, 说明 S 给大了; 若仍然
//   觉得"发橙"而 S 已经很大, 那就不是色度幅度问题而是色相问题, 该上 CCM 而不是
//   继续加 S。 —— 本轮用五之二给了一个便宜得多的近似, 见下。
//
//   裁剪用与 rgb_sharpen 完全相同的 16 位借位判溢出的写法, 正负两支都留足余量。
//
// ===========================================================================
// 五之二、红色偏向 (P_RED_SHIFT) —— "红偏橘"的便宜近似
//
//   *** 前提: 已经确认过"橘"不是本模块造成的 ***
//   均匀缩放色度向量是**逐位不改色相**的 —— 实测 (S=1.30):
//     {R,G,B}         S=1.00 色相    S=1.30 色相
//     (200,120,100)      12.0 度         12.0 度
//     (230,120,100)       9.2 度          9.2 度
//     (140, 80, 60)      15.0 度         15.0 度
//   所以 P_SAT_GAIN 调大调小都动不了色相; 唯一会动的路径是 R 撞 255 被裁, 而那条
//   **往橙的方向**跑 ((255,120,80) 从 13.7 度变成 15.8 度) —— 越加越糟。
//   橘是进本模块之前就有的。见下面"必须先做的另一条"。
//
//   *** 先做的另一条 (2026-10-06 实测, 优先级高于本参数) ***
//   按 rawdata.hex 整帧走 BLC(17) -> WB -> gamma:
//     现默认增益 17826/24718/17778 -> R/G/B 均值 78.7/84.4/48.4,
//       中间调整体色相 68.6 度 (黄), R 占优像素色相中位 40.5 度 (橙)
//     灰世界修正后               -> R/G/B 均值 54.9/53.5/54.2,
//       R 占优像素色相中位 19.2 度
//   B 只有 G 的 57%, 整幅画面压着 20 度的黄偏 —— 这才是"红偏橘"的主因, 而它
//   *** 本模块修不了 *** (增益在 wb_gain_3ch.v, 默认值在 ti60f225_oob_top.v,
//   且能由 VIO 的 vio0_r/g/b_gain 在线覆盖)。本参数是在白平衡已经调正之后
//   仍嫌红不够红时才用的。否则就是用一个色相误差去盖另一个色相误差。
//
//   *** 做什么 ***
//   把 **R 分量**的色度增量 |R-Y| 单独放大:
//     Y     = luma(R,G,B)
//     s     = sat_gain_at(Y)                     // G/B 用它
//     sr    = (R > Y) ? (s + (s >> P_RED_SHIFT)) : s
//     d_r   = round((R-Y) * sr / 2^14)
//     d_g/b = round((G/B-Y) * s / 2^14)          // 不动
//   红占优的像素 R 进一步离开 Y, 于是同时**更红**和**更饱和**, 对症状里
//   "不够红"和"发灰"两条正好一起对上。
//
//   *** 为什么限定 R > Y ***
//   不限定的话, 绿/蓝/青这类 R < Y 的像素 R 会被推小, 变成偏青 —— 得不偿失
//   (实测 (100,200,100) 的 R 会从 82 掉到 63)。限定之后中性色 (R == Y,
//   增量恒 0) 与 R 不占优的色**完全不动**。
//   在切换点 R == Y 处增量本身是 0, 两个增益给出一模一样的输出, 所以这个条件
//   判断 *** 不产生台阶 ***, 不会出现可见的色调边界。
//
//   *** 实测色相位移 (S=1.30, 度; 0=纯红 30=橙) ***
//     {R,G,B}         均匀    x1.125   x1.25    x1.5
//     (200,120,100)   12.0     11.1     10.5     9.3
//     (230,120,100)    9.2      9.2      9.2     9.2   <- R 已撞 255, 无位移
//     (180, 90, 70)   11.0     10.2      9.5     8.4
//     (160,110, 95)   13.6     12.7     11.9    10.6
//     (140, 80, 60)   15.0     14.1     13.2    11.7
//   位移量级是 1.5~3.3 度: 这是"回正一点", 不是"换个颜色"。要 10 度以上的
//   色相旋转只能上 CCM —— 那要新增模块和色卡标定, 本轮不做。
//
//   *** 代价, 必须知道 ***
//   1. 这不是色相旋转, 而是**沿 R 轴的拉伸**。R 占优的紫/品红会跟着更艳。
//   2. 保 Y 被破坏: R 多出来的量没有通道补偿, 红像素会略微变亮。这正是
//      "同时更红更饱和"的来源, 不是 bug; 代价是它与第二节"严格保 Y"的
//      说法只对 P_RED_SHIFT == 0 成立。
//   3. 时序: 这一级加在 sat_front (寄存器**之前**), 那一段的预算是本模块自己的
//      13.468 ns, 当前只用了 5~6 ns, 加一个 8 位比较器加一个 16 位加法器约
//      1~1.5 ns, 有余量。*** 它没有加在 sat_back (寄存器之后) ***, 那一段
//      对着 8.719 ns 的预算, 才是紧的那一侧。落点是刻意选的。
//
//   参数: P_RED_SHIFT, 增益 = 1 + 2^-P_RED_SHIFT
//     0 -> 关闭 (增益恰为 1.0, 与没有这个功能逐位相同)
//     1 -> x1.50    2 -> x1.25    3 -> x1.125   (越大越弱)
//   P_RED_SHIFT == 0 时整条 s_r 通路被常量传播优化掉, 不浪费逻辑。
//   前提: s + (s >> P_RED_SHIFT) 不越 16 位 -> 要求 P_SAT_GAIN <= 43690 (2.67x),
//         正常标定范围 (< 2.0) 里远远够。
// ===========================================================================
// 六、为什么必须插一级流水 (修正上一版的一处判断错误)
//
//   *** 上一版这里写的是"组合逻辑, 不插流水级 —— 这是刻意的, 不要去顺手加寄存器"。
//   那句话是错的, 上板直接翻车: 综合报出 10 条失败路径, 最差 slack -5.881 ns。***
//
//   实测 (outflow/ti60f225_oob.timing.rpt, 失败路径的累计延迟分解):
//     约束                 :  6.734 ns   (vid_clk_dvi2 -> hdmi_tx_slow_clk, 148.5MHz 侧采样)
//     数据路径             : 12.038 ns
//       其中 rgb_sharpen   : 0.389 -> 4.166 = 3.78 ns
//       其中 本模块         : 4.166 -> 12.427 = 8.26 ns   <== 12ns 里的 69%
//     逻辑级数             : 48
//
//   根因**不是资源** (全设计 Memory Block 149/256、XLR 37.46%、DSP 22/160, 都放得下),
//   是**本模块的组合深度**。而这一级偏偏接在一个 148.5 MHz 的采样寄存器前面
//   (ti60f225_oob_top.v 的 hdmi_tx_* 那一块用 hdmi_tx_slow_clk 采 rgb_datax2),
//   于是本模块全部的 Y -> 门控 -> delta -> adj -> 钳位 链都必须塞进 6.734 ns。
//
//   *** 为什么"简化算术"救不回来 *** —— 写下来免得下次又去试:
//   本模块的组合链是 Y(3 乘) -> 门控(1 乘 + 除) -> delta(1 乘) -> adj(加/钳),
//   串行 4 个乘加级。就算把门控整个去掉换成常数 S, 也只省下约 2.5 ns,
//   8.26 -> 5.8 ns, 加上 rgb_sharpen 的 3.78 仍是 9.6 ns, 对 6.734 ns 的约束
//   还差 43%。**差 87% 的违例不是靠"少算一点"能补的, 必须断链。**
//
//   断链位置: *** 切在 sat_delta 之后、adj_ch 之前 ***, 不是切在输出端。
//   记账 (约束 6.734 ns; required time = 6.734 + 捕获时钟路径 2.111 - 0.126 = 8.719):
//     输入侧: RAM 0.389 + rgb_sharpen 3.78 + [Y + 门控 + delta ≈ 5~6] -> 本模块的寄存器
//             这一段的约束是**本模块时钟自己的周期 13.468 ns**, 余量 3 ns 以上
//     输出侧: 本模块的寄存器 -> adj_ch(加/钳 ≈ 2) -> hdmi_tx_slow_clk 的 FF
//             发射时钟路径 2.170 + 时钟到 Q + 2 ≈ 4.7 ns, 对 8.719 ns 余量 4 ns
//   为什么不切在输出端: 那样输入侧要背 3.78 + 8.26 ≈ 12 ns 塞进 13.468 ns, 只剩 1 ns,
//   太紧; 而输出侧那个钳位又白白占着一段本来很宽裕的预算。
//
//   *** 延迟: 本模块现在是 1 拍, 标志与数据一起延迟 1 拍。***
//   红线 (见 debayer_top_wbg_2to1.v 文件头) 说的是"标志与数据的**相对**错拍不能动",
//   不是"延迟必须是 0"。四个标志和数据同步延迟同样的拍数, 相对错拍就不变。
//   下游 rgb_vs/hs/de/valid/datax2 的**唯一**消费者是 hdmi_tx_* 那一块 (同源同拍),
//   所以整幅画面只是晚 1 个 vid_clk_dvi2 周期出现, 相对关系一个都没变。
//   旁路 (P_BYPASS=1) 走**同一级寄存器**: 输入原始字也被寄存, 所以旁路与直通的拍数
//   严格相同 —— 这正是红线要求的, 由 tb_rgb_saturate.v 的检查 2 断言。
//
//   万一还要压: 本模块的 1 拍只能再拆成 2 拍 (Y+门控 / delta+adj)。
//   但那样流水线继续变长, 先确认下游没有按绝对拍数标定的东西再说。
//   *** 最省事的退路: 顶层把 .P_BYPASS 接 1'b1, 整个 sat_pix 逻辑被常量传播优化掉,
//   时序立刻回到加本模块之前的状态 (只留那一级寄存器)。代价是丢掉红色调整。***
//
// 数据约定: {奇列{B,G,R}, 偶列{B,G,R}}, 每像素为 {B,G,R} 且 **R 在最低字节**
//   (由 debayer_top_wbg_2to1.v 的 rgb_datax2_o 定义)。写模型或激励时最容易在
//   这里翻车: 顺手把最高字节当 R, 亮度系数 77/29 就换位了。只有当 R != B 时才
//   看得出来, 所以任何对拍都不能用 R==B 的激励。
//
// P_BYPASS = 1 即旁路: 只 mux 数据、不动标志, 且 mux 的是**同一级寄存器的输出**,
//   所以拍数完全一致。留这个开关是为了结构回归 —— 它能不依赖算术正确性就把这一级摘掉。
//
// 参数前提 (写死在参数里, 综合常量求值, 不满足会得到无意义的结果):
//   P_SAT_GAIN >= P_SAT_GAIN_LO  否则两增益之差的 16 位减法下溢
//   P_Y_HI >  P_Y_LO             否则中间分支永不进入 (被前两个 if 覆盖), 不除零
//   P_Y_HI - P_Y_LO 取 2 的幂    否则斜坡的除法退化成真除法器, 白丢时序 (见第三节)
//   P_SAT_GAIN_LO == P_SAT_GAIN 时门控退化为无门控, 是合法的"只调饱和度"配置
//   P_RED_SHIFT > 0 时 R 通道的增益是 s 的 (1 + 2^-P_RED_SHIFT) 倍, 于是**保 Y
//     不再严格成立** (红像素会略微变亮)。0 时与不要这个功能逐位相同。见五之二
//
// TODO: P_SAT_GAIN / P_SAT_GAIN_LO / P_Y_LO / P_Y_HI 都是参数, 改一次要重综合。
//       要在线调就得挂到 VIO 上, 但 VIO 核是 Efinity 生成的 (debug_edb_top),
//       加探针必须在 Debugger wizard 里重新生成核, 改 RTL 改不出来; 而且当前核的
//       4 个输出 (vio0_r/g/b_gain + vio0_gamma_sel) 已经全部占用, 没有空闲探针。
//       饱和度标定收敛后不会反复改, 参数形式够用。
/////////////////////////////////////////////////////////////////////////////

module rgb_saturate
#(
	parameter [15:0]	P_SAT_GAIN		= 16'd21299,	// Q2.14, 1.30; 16384 = 1.0 = 直通
	parameter [15:0]	P_SAT_GAIN_LO	= 16'd8192,		// Q2.14, 0.50; 暗部(Y<=P_Y_LO)的色度增益
	parameter [ 7:0]	P_Y_LO			= 8'd32,		// 暗部门控下限: 以下用 P_SAT_GAIN_LO
	parameter [ 7:0]	P_Y_HI			= 8'd96,		// 暗部门控上限: 以上用 P_SAT_GAIN
													// (P_Y_HI - P_Y_LO) = 64 = 2^6, 除法变移位
	parameter integer	P_RED_SHIFT		= 2//,			// R 通道额外色度增益 = 1 + 2^-P_RED_SHIFT
													// 0 = 关闭; 1 = x1.5; 2 = x1.25; 3 = x1.125
													// 只对 R > Y 的像素生效, 见文件头五之二
	// parameter			P_BYPASS		= 1'b0			// 1 = 只 mux 数据, 不调饱和度
)
(
	input						i_pclk,
	input						i_arstn,		// 异步复位, 低有效
	input 						P_BYPASS,
	
	input						i_vs,
	input						i_hs,
	input						i_de,
	input						i_valid,
	input	[47:0]				i_datax2,		// {奇列{B,G,R}, 偶列{B,G,R}}

	output						o_vs,
	output						o_hs,
	output						o_de,
	output						o_valid,
	output	[47:0]				o_datax2
);

	//======================================================================
	// 门控斜坡的两个常量
	//   P_RAMP_SHIFT 必须等于 log2(P_Y_HI - P_Y_LO), 现在两者之差写死是 64 -> 6。
	//   *** 改 P_Y_HI / P_Y_LO 时这里必须同步改 ***, 否则斜坡斜率整个错掉,
	//   而且因为它是个移位, 位精确对拍也看不出来 (模型照抄同样的常量就会一起错)。
	//   之所以写成移位而不是 num / (P_Y_HI - P_Y_LO): / 常数要赌综合器认出来,
	//   认不出来就是这条路径上最重的一块。见 sat_gain_at 里的注释。
	//======================================================================
	localparam			P_RAMP_SHIFT	= 6;
	localparam	[7:0]	P_RAMP_HALF		= (P_Y_HI - P_Y_LO) >> 1;	// 四舍五入常数

	//======================================================================
	// P_RED_SHIFT == 0 表示关闭红色偏向。
	// 写成编译期常量, 综合时整条 s_r 通路被常量传播删掉 (见文件头五之二)。
	//======================================================================
	localparam			P_RED_ON		= (P_RED_SHIFT != 0);

	//======================================================================
	// 亮度: BT.601, 系数和 = 256, 加 128 做四舍五入
	//   必须与 rgb_sharpen.v 里的 luma() 逐字相同 —— 两个模块对"什么是 Y"
	//   的认识不一致的话, 锐化与饱和度就会朝同一幅画的相反方向掰。
	//   77*255 + 150*255 + 29*255 + 128 = 65408, 32 位表达式不会溢出。
	//======================================================================
	function [7:0] luma;
		input [7:0] r;
		input [7:0] g;
		input [7:0] b;
		begin
			luma = (77*r + 150*g + 29*b + 128) >> 8;
		end
	endfunction

	//======================================================================
	// 当前亮度下生效的色度增益 (Q2.14) —— 暗部门控的线性斜坡
	//   见文件头第三节。斜坡而不是硬开关, 是为了不出现可见的饱和度突变边界。
	//
	//   *** 位宽: 两个乘数都必须显式零扩展到 25 位 ***
	//   Verilog 的 a*b 结果宽度是 max(width(a), width(b)) 而不是两者之和。
	//   写成 "(P_SAT_GAIN - P_SAT_GAIN_LO) * t" 会得到一个 **16 位** 的乘积,
	//   而 13107 * 64 = 838848 早就越了 16 位 —— 会被静默截断, 门控斜率全错,
	//   而且位精确对拍也查不出来 (模型照抄同样的写法就会一起错)。
	//   这正是 sat_delta() 里已经警告过的同一个坑。
	//
	//   除法用常数 (P_Y_HI - P_Y_LO): 取 2 的幂时综合成一次移位。
	//   分子最宽 65535 * 255 = 16711425 < 2^25。加半个分母做四舍五入。
	//   边界: P_Y_HI == P_Y_LO 时中间分支永不进入 (前两个 if 已覆盖全域), 不除零。
	//======================================================================
	function [15:0] sat_gain_at;
		input [7:0] yy;
		reg  [ 8:0] t;
		reg  [24:0] num;
		begin
			if (yy <= P_Y_LO)
				sat_gain_at = P_SAT_GAIN_LO;
			else if (yy >= P_Y_HI)
				sat_gain_at = P_SAT_GAIN;
			else begin
				t   = {1'b0, yy} - {1'b0, P_Y_LO};
				num = {9'b0, (P_SAT_GAIN - P_SAT_GAIN_LO)} * {16'b0, t}
				      + {17'b0, (P_RAMP_HALF)};
				// *** 2026-10-06: 原来是 num / {17'b0, (P_Y_HI - P_Y_LO)},
				// 改成写死的 >> P_RAMP_SHIFT。 ***
				// 原来的写法是在**赌**综合器认出"除数是常数 64"并优化成移位。
				// 万一它老实综合出一个 25 位除法器, 那就是这条路径上最重的一块,
				// 而这条路径的预算只有本模块自己一个 13.468 ns 周期 (见第六节)。
				// 验证方法上的教训: 写 / 常数时, 仿真和 Python 模型都算得对,
				// 只有综合结果才知道有没有变成移位 —— 这种事不能在 RTL 层赌。
				sat_gain_at = P_SAT_GAIN_LO + (num >> P_RAMP_SHIFT);
			end
		end
	endfunction

	//======================================================================
	// 一个通道的色度增量: {sgn, amt}
	//   d = c - Y (9 位补码), amt = round(|d| * s / 2^14), sgn = d 的符号位
	//   s 由调用方按亮度算好传进来。G/B 用同一个 s; R 在 P_RED_SHIFT != 0 时
	//   用一个略大的 sr (见文件头五之二) —— 那是**刻意的**色相偏置, 不是笔误。
	//   除这一条外三通道必须共用同一个 Y 支撑, 否则就不叫保 Y 了。
	//   与 rgb_sharpen.v 的 sharp_amt() 同构: 显式把 |d| 零扩展到 25 位再做
	//   乘法, 别指望工具按上下文把 "mag(9位) * s(16位)" 自动撑到 25 位 ——
	//   写清楚省得换工具后静默截断。
	//   上限 255 * 65535 = 16711425 < 2^24, 加 8192 仍不越 25 位; 商 <= 1020,
	//   11 位幅值足够。
	//======================================================================
	function [11:0] sat_delta;
		input [7:0]  ch;
		input [7:0]  yy;
		input [15:0] s;
		reg   [8:0] dlt;
		reg   [8:0] mag;
		reg  [24:0] scl;
		begin
			dlt = {1'b0, ch} - {1'b0, yy};				// 9 位补码
			mag = dlt[8] ? (~dlt + 9'd1) : dlt;			// |d|, 0..255
			scl = {16'b0, mag} * s + 25'd8192;			// 四舍五入后 >>14
			sat_delta = {dlt[8], scl[24:14]};
		end
	endfunction

	//======================================================================
	// 把增量加到 **Y** 上 (不是加到原通道上), 饱和到 [0,255]
	//   直接沿用 rgb_sharpen.v 的 adj_ch(): 16 位中间量, 正负两支都留足余量,
	//   靠最高位判下溢。S=16384 时 amt 恒等于 |d|, 于是正好回推出 c。
	//======================================================================
	function [7:0] adj_ch;
		input [7:0]  ch;							// 传进来的是 Y
		input [13:0] amt;
		input        sgn;
		reg  [15:0]  wide;
		begin
			wide = sgn ? ({8'b0, ch} - {2'b0, amt}) : ({8'b0, ch} + {2'b0, amt});
			adj_ch = wide[15] ? 8'd0 : ((wide[14:0] > 15'd255) ? 8'd255 : wide[14:0]);
		end
	endfunction

	//======================================================================
	// 一个像素: {B,G,R} -> 同一个 Y 支撑下的三个新通道
	//   三个通道共用同一个 Y (同一个 d 的基准) 和同一个 s (同一个放大倍数),
	//   这是 Y 保持的前提; 每个通道各算各的 Y 会变成逐通道缩放, 那样灰不变但色相会漂。
	//
	// *** 为了断链, 这里拆成前/后两段, 中间插一级寄存器 ***
	//   前半段 sat_front: {B,G,R} -> {Y, db, dg, dr}   (44 位)
	//   后半段 sat_back : {Y, db, dg, dr} -> {B,G,R}
	//   拆分点见文件头第六节。两段合起来的**数值结果与原版逐位相同** ——
	//   只是中间多存了一份 (Y, 三个增量), 算法一点没动。
	// ======================================================================

	// 前半段: Y -> 门控 -> 三个色度增量。位序 {Y[7:0], db[11:0], dg[11:0], dr[11:0]}
	function [43:0] sat_front;
		input [23:0] px;							// {B, G, R}
		reg  [7:0]  rr, gg, bb, yy;
		reg [15:0]  s, sr;
		begin
			rr = px[ 7: 0];
			gg = px[15: 8];
			bb = px[23:16];
			yy = luma(rr, gg, bb);
			s  = sat_gain_at(yy);					// 暗部门控在这里生效
			// R 占优时把 R 的色度增量放大: 同时更红、更饱和。见文件头五之二。
			// 限定 R > Y 是为了不把绿/蓝/青推向青; 切换点 R == Y 处增量恒为 0,
			// 所以这个判断不产生台阶。
			// P_RED_ON 是编译期常量, P_RED_SHIFT == 0 时整条被常量传播删掉。
			// 落点在 sat_front (寄存器之前, 预算 13.468 ns), **不是** sat_back
			// (寄存器之后, 预算 8.719 ns) —— 见文件头五之二第 3 条。
			sr = (P_RED_ON && (rr > yy)) ? (s + (s >> P_RED_SHIFT)) : s;
			sat_front = { yy,
			              sat_delta(bb, yy, s ),
			              sat_delta(gg, yy, s ),
			              sat_delta(rr, yy, sr) };
		end
	endfunction

	// 后半段: 把三个增量加到 Y 上, 钳位后打包回 {B, G, R} (R 在最低字节)
	function [23:0] sat_back;
		input [43:0] f;
		reg  [7:0]  yy;
		begin
			yy = f[43:36];
			sat_back = { adj_ch(yy, {3'b0, f[34:24]}, f[35]),		// B
			             adj_ch(yy, {3'b0, f[22:12]}, f[23]),		// G
			             adj_ch(yy, {3'b0, f[10: 0]}, f[11]) };	// R
		end
	endfunction

	//======================================================================
	// 唯一的流水级: 四个标志 + 原始字 + 两个像素的前半段结果, 一起寄存
	//   *** 原始字必须也寄存 *** —— 旁路要 mux 的是**这一级的输出**,
	//   不是模块输入, 否则旁路比直通少 1 拍, 直接踩红线。
	//   P_BYPASS 是编译期常量, 综合会把用不到的那一半整个优化掉, 不浪费触发器。
	//======================================================================
	reg				r_vs, r_hs, r_de, r_valid;
	reg	[47:0]		r_dat;
	reg	[43:0]		r_f_e, r_f_o;

	always @(posedge i_pclk or negedge i_arstn)
	begin
		if (!i_arstn) begin
			r_vs    <= 1'b0;
			r_hs    <= 1'b0;
			r_de    <= 1'b0;
			r_valid <= 1'b0;
			r_dat   <= 48'd0;
			r_f_e   <= 44'd0;
			r_f_o   <= 44'd0;
		end else begin
			r_vs    <= i_vs;
			r_hs    <= i_hs;
			r_de    <= i_de;
			r_valid <= i_valid;
			r_dat   <= i_datax2;
			// 低位 24 位 = 偶列, 高位 24 位 = 奇列
			r_f_e   <= sat_front(i_datax2[23: 0]);
			r_f_o   <= sat_front(i_datax2[47:24]);
		end
	end

	wire	[23:0]	w_pix_e = sat_back(r_f_e);
	wire	[23:0]	w_pix_o = sat_back(r_f_o);

	assign	o_datax2 = P_BYPASS ? r_dat : {w_pix_o, w_pix_e};

	assign	o_vs	= r_vs;
	assign	o_hs	= r_hs;
	assign	o_de	= r_de;
	assign	o_valid	= r_valid;

endmodule
