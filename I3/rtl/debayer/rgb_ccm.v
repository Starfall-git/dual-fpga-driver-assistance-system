/////////////////////////////////////////////////////////////////////////////
// rgb_ccm.v —— 3x3 色彩校正矩阵 (Color Correction Matrix), 本工程用于**色相调节**
//
// 位置: 插在 rgb_sharpen **之后**、rgb_saturate **之前**:
//         debayer_top_wbg_2to1 (去马赛克+WB+gamma) -> rgb_sharpen
//           -> [ rgb_ccm ] -> rgb_saturate -> hdmi_tx_* 消费块
//
// *** 本模块是 2 拍流水 (标志与数据同步延迟 2 拍), 不是组合直通。***
//     理由见第六节。
//
// ===========================================================================
// 一、为什么需要这一级
//
//   病例: 用户报"红色有点偏橘"。
//
//   前两轮的处置与实测结论 (不要重复走) :
//     - rgb_saturate 的 P_SAT_GAIN (Y 保持的色度拉伸) : 实测证明**均匀色度缩放
//       精确保持色相**, 所以它既造成不了也治不了偏色。唯一会移动色相的路径是
//       R 撞 255 的钳位, 而它把红色推**向**橙色, 是反方向。
//     - rgb_saturate 的 P_RED_SHIFT (R 通道额外色度增益) : 确实把红色像素往红的
//       方向推了 1.5~3.3 度, 但幅度有限, 且它同时破坏了 Y 守恒。
//
//   而 rgb_saturate.v 文件头自己就写着: "3x3 色彩矩阵才是治'色相偏'的正规工具"。
//   本模块就是补上这件正规工具。有了它, rgb_saturate 那边的 P_RED_SHIFT 应当
//   设成 0 关掉 —— 色相只由一处负责, 否则两条通路叠加、互相盖, 标定没法做。
//
//   *** 但它治不了"偏橘"的主因 ***
//   实测: 当前 WB 默认增益 17826/24718/17778 给出 R/G/B 均值 78.7/84.4/48.4,
//   整体**黄偏约 20 度**。这才是主因。灰世界要求约 14254/16048/40960。
//   请先用 VIO 的 vio0_r/g/b_gain 在线把灰/白物体调成中性, **再**动 CCM 系数。
//   拿 CCM 去盖白平衡的错, 只会把误差混进矩阵里, 以后拆不开。
//
// ===========================================================================
// 二、算法与定点格式
//
//   R' = clamp( (M_RR*R + M_RG*G + M_RB*B + 8192) >>> 14, 0, 255 )
//   G' = clamp( (M_GR*R + M_GG*G + M_GB*B + 8192) >>> 14, 0, 255 )
//   B' = clamp( (M_BR*R + M_BG*G + M_BB*B + 8192) >>> 14, 0, 255 )
//
//   9 个系数都是 **Q2.14 有符号** (16384 = 1.0), 值域 [-2.0, +1.99994]。
//   选 Q2.14 是为了与本工程既有的 wb_gain_3ch.v / rgb_saturate.v 一致 ——
//   "16384 = 1.0" 已经是这个工程的肌肉记忆, 多引入一个定点标度只会制造换算错误。
//   注意兄弟工程 rtl/isp/isp_ccm.v 用的是 **Q2.8** (256 = 1.0) : 把它的系数
//   抄过来必须 **乘 64**。直接把 256 填进这里, 增益是 1/64, 画面几乎全黑。
//
//   *** 恒等矩阵必须逐位等于直通 *** —— 这是恒等式而非近似, 也是本模块的红线:
//   M_RR = M_GG = M_BB = 16384, 其余为 0 时, 每通道
//       s = 16384*v,  (16384*v + 8192) >>> 14 = v     (0 <= v <= 255)
//   因为 16384*v + 8192 = 16384*(v + 0.5), 右移 14 位向下取整正好回到 v。
//   所以那个舍入常数**只能是 8192 = 2^13**: 写成 16384 (2^14) 会让整幅画面抬亮
//   一级, 写成 4096 会压暗一级。同样的红线在 rgb_saturate.v (S=16384 直通) 和
//   wb_gain_3ch.v ((1<<(SHIFT-1)) 舍入) 里各出现过一次。
//
// ===========================================================================
// 三、位宽账 (本工程的已知陷阱)
//
//   本工程文档反复记录过: Verilog 里 `a*b` 的结果宽度是 max(w(a), w(b)),
//   **不是**宽度之和。写错会静默截断, 而且照抄 RTL 写的模型会跟着一起错,
//   位精确对拍全绿 (ti60f225_oob_top.v:1039 记过这个教训)。
//
//   系数 signed[15:0], 像素 8 bit 无符号 (0..255) :
//     单个乘积最坏 |32768 * 255|        = 8 355 840  -> 需 24 bit; 本模块给 CW=25
//     三乘积和  最坏 |3 * 8 355 840|    = 25 067 520 -> 需 26 bit; 本模块给 SW=27
//     加 8192 后                        = 25 075 712 -> 仍在 26 bit 内
//     >>>14 之后的范围                  = [-1530, +1530] -> 钳位到 [0,255]
//   各留 1 bit 余量, 不会溢出。
//
//   **两个乘数都必须显式扩到 CW 位, 且都必须是有符号的**:
//     系数符号扩展, 像素零扩展。见 ccm_mul()。
//   不能写成 `m * $signed({1'b0,c})` —— 16 位 x 9 位 在自决定宽度下只有 16 位,
//   立刻截断。兄弟工程 isp_ccm.v:34 就是那个写法, 它没坏只是因为 LHS 的 24 位
//   上下文恰好把操作数撑宽了 —— 那是**侥幸**, 不是正确。本模块不依赖上下文宽度。
//
//   只要有一个乘数不是 signed, 整个表达式就变无符号, 负系数会被**零扩展**而非
//   符号扩展, 全部算错。所以两处都写 $signed()。
//
//   **右移必须写 `>>>` (算术右移) 而不是 `>>`**: `>>` 是逻辑右移, 负值右移会补 0,
//   变成一个巨大的正数, 钳位后统一爆成 255 —— 所有带负系数的像素全部变白,
//   而且位精确对拍**查不出来** (模型照抄同样的写法就一起错)。
//
// ===========================================================================
// 四、字节序 (最危险的坑) 与端口约定
//
//   本工程 (debayer_top_wbg_2to1.v:248-249) :
//     i_datax2[23: 0] = 偶列像素 {B, G, R}
//     i_datax2[47:24] = 奇列像素 {B, G, R}
//   *** 每个像素的 R 都在最低字节 ***
//
//   兄弟工程 isp_ccm.v 的约定**相反**: 它是 {R,G,B} 且 R 在高位 p[29:20]。
//   照抄它的提取顺序 -> R/B 互换 -> 色相整个错, 而且因为照抄 RTL 写的模型会
//   一起错, 位精确对拍是绿的。所以**对拍激励不能用 R == B 的颜色**。
//
//   两个像素共用同一套函数, 各调用一次; 与 rgb_saturate.v 的 sat_front 同构。
//
// ===========================================================================
// 五、怎么用它调色相 —— 系数从哪来
//
//   没有色卡, 所以最实用的用法是"给一个旋转角, 出 9 个系数"。生成脚本:
//     rtl/debayer/sim/ccm_gen.py
//       python ccm_gen.py --hue 20        # 出一组系数
//       python ccm_gen.py --table         # 打印 -30..+30 度的现成参数表
//
//   矩阵构造是**保 BT.601 亮度**且**保中性色**的色度平面旋转 (与 SVG
//   feColorMatrix 的 hueRotate 同一构造, 但把 Rec.709 的权重换成工程里的
//   w = (77, 150, 29)/256) 。**必须用 77/256 这三个数, 不能用 0.299/0.587/0.114
//   的十进制近似** —— 差 1e-3 会让系数偏十几个 LSB, 保的就不是本工程
//   Y = (77R + 150G + 29B + 128) >> 8 定义的那个亮度了。ccm_gen.py 用的是前者。
//   已数值验证三条不变量 (20 万随机像素 x 5 个角度, 误差 0):
//     亮度精确保守、色度向量模长精确保守、灰 (R==G==B) 精确保灰。
//   注意: 该矩阵在 R^3 里**不是**正交阵 (|M^T M - I| ~ 0.14) —— 那是"沿 1 方向
//   投影"在非正交基下的表象, 不影响上面三条不变量, 别误判成写错了。
//
//   *** 符号约定 ***  theta > 0 就是**色相朝红** (HSV 色相角减小), 幅度近似 1:1。
//   注意色相角与色度平面旋转角不是同一个度量, 实测位移比标称角度略小
//   (theta=+20 实测中位 17.3 度) , 标定时按实测走, 不要按标称值。
//
//   现成系数 (**由 `python ccm_gen.py --hue 20` 生成, 不要手算**) :
//     theta = +20 度  (色相朝红, 治"红偏橘"的首选起点)
//       M_RR=16885  M_RG= 3851  M_RB=-4352
//       M_GR=-1126  M_GG=15054  M_GB= 2456
//       M_BR= 4491  M_BG=-3344  M_BB=15237
//   实测效果 (定点通路, 逐位): 橙色 (255,140,60) 24.6 度 -> 8.7 度;
//   黄色 (200,180,90) 49.1 -> 30.7; 3 万随机像素色相位移中位 17.3 度。
//
//   定点通路本身的误差 (3 万随机像素 x 3 个角度) : 与浮点矩阵最大通道差 1 LSB,
//   逐通道平均差 0.010, 99% 逐通道完全一致。Q2.14 的量化误差在这个用法里可忽略。
//
// ===========================================================================
// 六、为什么是 2 拍流水, 以及寄存器为什么必须在**输出端**
//
//   为什么开 2 级: 本工程的 rgb_saturate 就是因为"组合直通"上板时序翻车才改成
//   1 拍的 (rgb_saturate.v:9-10)。而这条链路**至今没有过任何 place/route 报告**
//   (已核实: outflow/ 下没有 ti60f225_oob.timing.rpt, 日志里 slack 出现 0 次) ,
//   所以没有任何数据支撑"1 级够用"的断言。拆 2 级是保守选择。
//
//   *** 关于预算的正确说法 ***: 拆 2 级**不是**把每级预算变成 6.7 ns —— 每一级
//   的组合都必须各自塞进一个完整的 13.468 ns (vid_clk_dvi2) 周期; 拆 2 级的
//   意义是**允许总组合深度到 26.9 ns**。别把这句话理解反了。
//
//   *** 寄存器必须在输出端, 这一点与 rgb_saturate 不同, 容易搞错 ***
//   若本模块只在输入端寄存、输出是组合的, 则下游路径会变成
//   "CCM 组合 + rgb_saturate.sat_front 组合"串成一条超长路径, 比不加这一级还糟。
//   本模块两级各自输出寄存, 所以 CCM -> rgb_saturate 的那条路径是从寄存器出发的。
//
//   插 2 拍是**安全**的 —— 已查证, 不是推测:
//     - vid_clk_dvi2 = 13.468 ns 与 hdmi_tx_slow_clk = 6.734 ns (ti60f225_oob.sdc:11-12)
//       来自同一个 USER_PLL, **严格 2:1 且同相**。移位整数个 vid_clk_dvi2 周期
//       = 移位整数个慢时钟周期 -> 采样相位偏移为**零**。
//       (sdc:24 把这条 CDC 设成 -exclusive, 工具不分析它; 但这里根本不需要分析。)
//     - 下游唯一的消费者 (ti60f225_oob_top.v:1124-1152) : pos_vs 是
//       {rgb_vs_r,rgb_vs} == 2'b01 的**同步上升沿检测**, vid_cnt 每帧由 pos_vs
//       重新同步, hdmi_tx_vs/hs/de 是纯寄存器副本。**没有任何绝对拍数假设**。
//     - rgb_* 上没有别的消费者, 也没有 VIO / LA 探针。
//   唯一要守的红线: **5 个信号 (vs/hs/de/valid/datax2) 严格同拍移相同的拍数**。
//
// ===========================================================================
// 七、P_BYPASS
//   1 = 只 mux 数据, 不调色。**延迟链不变** —— 旁路走的是同一级寄存器的原始字,
//   不是模块输入, 否则旁路比直通少 2 拍, 直接踩 debayer_top_wbg_2to1.v:15-21
//   那条"标志与数据的相对错拍不能动"的红线。
//   上板若看到彩色噪声, 把它改成 1'b1 重综合, 就能立刻定位是不是这一级。
//***************************************************************************
module rgb_ccm #(
	// Q2.14 有符号, 16384 = 1.0, 值域 [-2.0, +1.99994]。默认 = 恒等矩阵 (逐位直通)
	parameter signed [15:0]	M_RR = 16'sd16384,	// R' 对 R 的系数
	parameter signed [15:0]	M_RG = 16'sd0,		// R' 对 G
	parameter signed [15:0]	M_RB = 16'sd0,		// R' 对 B
	parameter signed [15:0]	M_GR = 16'sd0,
	parameter signed [15:0]	M_GG = 16'sd16384,
	parameter signed [15:0]	M_GB = 16'sd0,
	parameter signed [15:0]	M_BR = 16'sd0,
	parameter signed [15:0]	M_BG = 16'sd0,
	parameter signed [15:0]	M_BB = 16'sd16384//,
	// parameter				P_BYPASS = 1'b0		// 1 = 只 mux 数据, 延迟链不变
)(
	input					i_pclk,
	input					i_arstn,			// 异步复位, 低有效
	input  					P_BYPASS,
	input					i_vs,
	input					i_hs,
	input					i_de,
	input					i_valid,
	input	[47:0]			i_datax2,			// {奇列{B,G,R}, 偶列{B,G,R}}
	output					o_vs,
	output					o_hs,
	output					o_de,
	output					o_valid,
	output	[47:0]			o_datax2
);

	// 位宽见文件头第三节
	localparam integer	CW	= 25;		// 单乘积宽度
	localparam integer	SW	= 27;		// 三乘积和宽度

	//======================================================================
	// 系数 x 像素: 两个操作数**显式**扩到 CW 位, 且都转成有符号
	//   系数: 符号扩展 (负系数必须保持补码)
	//   像素: 零扩展 (0..255 恒为正)
	// 不写成 m * $signed({1'b0,c}) —— 那是靠 LHS 上下文撑宽的侥幸写法。
	//======================================================================
	function signed [CW-1:0] ccm_mul;
		input	signed [15:0]	m;
		input			[ 7:0]	c;
		begin
			ccm_mul = $signed({{(CW-16){m[15]}}, m}) * $signed({{(CW-8){1'b0}}, c});
		end
	endfunction

	//======================================================================
	// 三乘积 + 舍入 + 算术右移 + 钳位
	//   *** >>> 不是 >> ***  见文件头第三节: 写 >> 会让所有负系数像素爆成 255,
	//   而且位精确对拍查不出来。
	//   8192 = 2^13 是让"恒等矩阵逐位直通"成立的唯一取值, 别改。
	//======================================================================
	function [7:0] ccm_fin;
		input	signed [CW-1:0]	p0, p1, p2;
		reg		signed [SW-1:0]	s;
		begin
			// 25 -> 27 位符号扩展后再相加, 不依赖上下文宽度
			s = $signed({{(SW-CW){p0[CW-1]}}, p0})
			  + $signed({{(SW-CW){p1[CW-1]}}, p1})
			  + $signed({{(SW-CW){p2[CW-1]}}, p2});
			s = (s + 27'sd8192) >>> 14;
			if      (s < 27'sd0  ) ccm_fin = 8'd0;
			else if (s > 27'sd255) ccm_fin = 8'd255;
			else                   ccm_fin = s[7:0];
		end
	endfunction

	//======================================================================
	// 取像素分通道。R 在**最低字节** —— 见文件头第四节, 别照抄兄弟工程的顺序。
	//======================================================================
	wire	[7:0]	w_e_r = i_datax2[ 7: 0];		// 偶列
	wire	[7:0]	w_e_g = i_datax2[15: 8];
	wire	[7:0]	w_e_b = i_datax2[23:16];
	wire	[7:0]	w_o_r = i_datax2[31:24];		// 奇列
	wire	[7:0]	w_o_g = i_datax2[39:32];
	wire	[7:0]	w_o_b = i_datax2[47:40];

	// 偶列像素的 9 个乘积
	wire signed [CW-1:0] w_e_R0 = ccm_mul(M_RR, w_e_r);
	wire signed [CW-1:0] w_e_R1 = ccm_mul(M_RG, w_e_g);
	wire signed [CW-1:0] w_e_R2 = ccm_mul(M_RB, w_e_b);
	wire signed [CW-1:0] w_e_G0 = ccm_mul(M_GR, w_e_r);
	wire signed [CW-1:0] w_e_G1 = ccm_mul(M_GG, w_e_g);
	wire signed [CW-1:0] w_e_G2 = ccm_mul(M_GB, w_e_b);
	wire signed [CW-1:0] w_e_B0 = ccm_mul(M_BR, w_e_r);
	wire signed [CW-1:0] w_e_B1 = ccm_mul(M_BG, w_e_g);
	wire signed [CW-1:0] w_e_B2 = ccm_mul(M_BB, w_e_b);

	// 奇列像素的 9 个乘积
	wire signed [CW-1:0] w_o_R0 = ccm_mul(M_RR, w_o_r);
	wire signed [CW-1:0] w_o_R1 = ccm_mul(M_RG, w_o_g);
	wire signed [CW-1:0] w_o_R2 = ccm_mul(M_RB, w_o_b);
	wire signed [CW-1:0] w_o_G0 = ccm_mul(M_GR, w_o_r);
	wire signed [CW-1:0] w_o_G1 = ccm_mul(M_GG, w_o_g);
	wire signed [CW-1:0] w_o_G2 = ccm_mul(M_GB, w_o_b);
	wire signed [CW-1:0] w_o_B0 = ccm_mul(M_BR, w_o_r);
	wire signed [CW-1:0] w_o_B1 = ccm_mul(M_BG, w_o_g);
	wire signed [CW-1:0] w_o_B2 = ccm_mul(M_BB, w_o_b);

	//======================================================================
	// 第 1 级: 只做乘法, 18 个乘积 (2 像素 x 9) 寄存。
	//   拆点选在乘法之后, 正好用上 DSP 块自带的输出寄存器。
	//======================================================================
	reg					r1_vs, r1_hs, r1_de, r1_valid;
	reg	[47:0]			r1_dat;				// 旁路用, 见文件头第七节

	reg signed [CW-1:0]	r1_e_R0, r1_e_R1, r1_e_R2;
	reg signed [CW-1:0]	r1_e_G0, r1_e_G1, r1_e_G2;
	reg signed [CW-1:0]	r1_e_B0, r1_e_B1, r1_e_B2;
	reg signed [CW-1:0]	r1_o_R0, r1_o_R1, r1_o_R2;
	reg signed [CW-1:0]	r1_o_G0, r1_o_G1, r1_o_G2;
	reg signed [CW-1:0]	r1_o_B0, r1_o_B1, r1_o_B2;

	always @(posedge i_pclk or negedge i_arstn)
	begin
		if (!i_arstn) begin
			r1_vs    <= 1'b0;
			r1_hs    <= 1'b0;
			r1_de    <= 1'b0;
			r1_valid <= 1'b0;
			r1_dat   <= 48'd0;
			r1_e_R0 <= {CW{1'b0}};  r1_e_R1 <= {CW{1'b0}};  r1_e_R2 <= {CW{1'b0}};
			r1_e_G0 <= {CW{1'b0}};  r1_e_G1 <= {CW{1'b0}};  r1_e_G2 <= {CW{1'b0}};
			r1_e_B0 <= {CW{1'b0}};  r1_e_B1 <= {CW{1'b0}};  r1_e_B2 <= {CW{1'b0}};
			r1_o_R0 <= {CW{1'b0}};  r1_o_R1 <= {CW{1'b0}};  r1_o_R2 <= {CW{1'b0}};
			r1_o_G0 <= {CW{1'b0}};  r1_o_G1 <= {CW{1'b0}};  r1_o_G2 <= {CW{1'b0}};
			r1_o_B0 <= {CW{1'b0}};  r1_o_B1 <= {CW{1'b0}};  r1_o_B2 <= {CW{1'b0}};
		end else begin
			r1_vs    <= i_vs;
			r1_hs    <= i_hs;
			r1_de    <= i_de;
			r1_valid <= i_valid;
			r1_dat   <= i_datax2;
			r1_e_R0 <= w_e_R0;  r1_e_R1 <= w_e_R1;  r1_e_R2 <= w_e_R2;
			r1_e_G0 <= w_e_G0;  r1_e_G1 <= w_e_G1;  r1_e_G2 <= w_e_G2;
			r1_e_B0 <= w_e_B0;  r1_e_B1 <= w_e_B1;  r1_e_B2 <= w_e_B2;
			r1_o_R0 <= w_o_R0;  r1_o_R1 <= w_o_R1;  r1_o_R2 <= w_o_R2;
			r1_o_G0 <= w_o_G0;  r1_o_G1 <= w_o_G1;  r1_o_G2 <= w_o_G2;
			r1_o_B0 <= w_o_B0;  r1_o_B1 <= w_o_B1;  r1_o_B2 <= w_o_B2;
		end
	end

	//======================================================================
	// 第 2 级: 三输入加法 + 舍入 + 移位 + 钳位, 结果寄存。
	//   *** 这一级的输出寄存器是必须的 *** —— 下游 rgb_saturate 的 sat_front
	//   是组合的, 若本模块输出是组合的, 两者会串成一条超长路径。见文件头第六节。
	//======================================================================
	reg					r2_vs, r2_hs, r2_de, r2_valid;
	reg	[47:0]			r2_dat;
	reg	[23:0]			r2_pix_e, r2_pix_o;

	always @(posedge i_pclk or negedge i_arstn)
	begin
		if (!i_arstn) begin
			r2_vs    <= 1'b0;
			r2_hs    <= 1'b0;
			r2_de    <= 1'b0;
			r2_valid <= 1'b0;
			r2_dat   <= 48'd0;
			r2_pix_e <= 24'd0;
			r2_pix_o <= 24'd0;
		end else begin
			r2_vs    <= r1_vs;
			r2_hs    <= r1_hs;
			r2_de    <= r1_de;
			r2_valid <= r1_valid;
			r2_dat   <= r1_dat;
			// 打包回 {B, G, R}, R 在最低字节
			r2_pix_e <= { ccm_fin(r1_e_B0, r1_e_B1, r1_e_B2),	// B
			              ccm_fin(r1_e_G0, r1_e_G1, r1_e_G2),	// G
			              ccm_fin(r1_e_R0, r1_e_R1, r1_e_R2) };	// R
			r2_pix_o <= { ccm_fin(r1_o_B0, r1_o_B1, r1_o_B2),
			              ccm_fin(r1_o_G0, r1_o_G1, r1_o_G2),
			              ccm_fin(r1_o_R0, r1_o_R1, r1_o_R2) };
		end
	end

	// 旁路 mux 的是**这一级的输出寄存器**, 不是模块输入 —— 见文件头第七节
	assign	o_datax2 = P_BYPASS ? r2_dat : {r2_pix_o, r2_pix_e};

	assign	o_vs	= r2_vs;
	assign	o_hs	= r2_hs;
	assign	o_de	= r2_de;
	assign	o_valid	= r2_valid;

endmodule
